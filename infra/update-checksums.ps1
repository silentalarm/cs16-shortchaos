# Resolves official release assets and pins their SHA256 into infra/checksums.env.
# Nothing in the build trusts a URL that was not resolved and hashed here.
#
#   powershell -File infra/update-checksums.ps1                       # all components
#   powershell -File infra/update-checksums.ps1 -Only XASH3D,CS16CLIENT
#       resolves just those and keeps the other lines of checksums.env untouched, so adding one
#       component does not mean re-downloading ~100 MB of archives.
[CmdletBinding()]
param(
    [string]$OutFile,
    [string[]]$Only,
    [switch]$KeepCache
)

$ErrorActionPreference = 'Stop'

# $PSScriptRoot is not available while parameters are bound, so it is resolved afterwards.
$root = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
if (-not $OutFile) { $OutFile = Join-Path $root 'checksums.env' }

$components = (Get-Content (Join-Path $root 'components.json') -Raw | ConvertFrom-Json).components
# `powershell -File script.ps1 -Only A,B` passes one string, `-Only A,B` in a session passes an
# array; splitting makes both work the same way.
if ($Only) {
    $Only = @($Only | ForEach-Object { $_ -split ',' } | ForEach-Object { $_.Trim() } | Where-Object { $_ })
}
$headers = @{ 'User-Agent' = 'cs16-youtube-build'; 'Accept' = 'application/vnd.github+json' }
$cacheDir = Join-Path $root '.cache'
New-Item -ItemType Directory -Force -Path $cacheDir | Out-Null

$releaseCache = @{}
$lines = @("# generated by infra/update-checksums.ps1 on $(Get-Date -Format o)")
$lines += '# docker buildx build --build-arg-file infra/checksums.env -t cs16-hlds:local .'

# With -Only the existing file is the base: unknown lines are preserved verbatim, so re-resolving
# one component never silently drops the pins of the others.
if ($Only) {
    if (-not (Test-Path $OutFile)) { throw "$OutFile does not exist, run without -Only first" }
    $resolved = @{}
    foreach ($line in Get-Content $OutFile) {
        if ($line -match '^([A-Za-z0-9_]+)=(.*)$') { $resolved[$matches[1]] = $matches[2] }
    }
    foreach ($name in $Only) {
        if (-not $components.PSObject.Properties.Name.Contains($name)) {
            throw "-Only $name : no such component in components.json"
        }
    }
    $lines = @("# generated by infra/update-checksums.ps1 on $(Get-Date -Format o)")
    $lines += "# docker buildx build --build-arg-file infra/checksums.env -t cs16-hlds:local ."
} else {
    $resolved = @{}
}

foreach ($name in $components.PSObject.Properties.Name) {
    if ($Only -and -not ($Only -contains $name)) { continue }
    $component = $components.$name
    $cacheKey = "$($component.repo)|$($component.tag)"

    if (-not $releaseCache.ContainsKey($cacheKey)) {
        $apiUrl = if ($component.tag) {
            "https://api.github.com/repos/$($component.repo)/releases/tags/$($component.tag)"
        } else {
            "https://api.github.com/repos/$($component.repo)/releases/latest"
        }
        $releaseCache[$cacheKey] = Invoke-RestMethod -Uri $apiUrl -Headers $headers -TimeoutSec 60
    }

    $release = $releaseCache[$cacheKey]
    $asset = $release.assets | Where-Object { $_.name -match $component.asset } | Select-Object -First 1
    if (-not $asset) {
        throw "$name : no asset matching '$($component.asset)' in $($component.repo) $($release.tag_name)"
    }

    $file = Join-Path $cacheDir $asset.name
    # GitHub publishes the SHA256 of every asset. A cached file from an older build hashes to
    # something else, and pinning that hash produces a build that can never download again - which is
    # exactly how the streaming image broke on the rolling Xash3D "continuous" tag. The digest from
    # the API decides whether the cached copy is still the asset the URL points at.
    $expected = if ($asset.digest) { $asset.digest -replace '^sha256:', '' } else { '' }
    $stale = $true
    if (Test-Path $file) {
        $cachedSha = (Get-FileHash -Path $file -Algorithm SHA256).Hash.ToLower()
        $stale = ($expected -ne '') -and ($cachedSha -ne $expected)
    }
    if ($stale) {
        Write-Host "downloading $($asset.name) ..."
        Invoke-WebRequest -Uri $asset.browser_download_url -OutFile $file -Headers $headers -TimeoutSec 600
    }

    $sha = (Get-FileHash -Path $file -Algorithm SHA256).Hash.ToLower()
    if ($expected -ne '' -and $sha -ne $expected) {
        throw "$name : $($asset.name) hashed to $sha but GitHub reports $expected - the CDN served another build, retry later"
    }
    Write-Host ("{0,-14} {1,-14} {2}" -f $name, $release.tag_name, $asset.name)

    if (-not $component.tag) {
        Write-Host "  pin this tag in infra/components.json: $($release.tag_name)" -ForegroundColor Yellow
    }

    $resolved["$($name)_URL"] = $asset.browser_download_url
    $resolved["$($name)_SHA256"] = $sha
}

# Component order from components.json, so the file is stable and diff-friendly.
$written = @{}
foreach ($name in $components.PSObject.Properties.Name) {
    foreach ($suffix in @('_URL', '_SHA256')) {
        $key = "$name$suffix"
        if ($resolved.ContainsKey($key)) { $lines += "$key=$($resolved[$key])"; $written[$key] = $true }
    }
}
$dropped = @($resolved.Keys | Where-Object { -not $written.ContainsKey($_) })
if ($dropped.Count -gt 0) {
    Write-Host "warning: dropped stale keys that no longer match components.json: $($dropped -join ', ')" -ForegroundColor Yellow
}

Set-Content -Path $OutFile -Value $lines -Encoding ascii
Write-Host "`nwrote $OutFile"
Write-Host "next: docker buildx build --build-arg-file infra/checksums.env -t cs16-hlds:local ."

if (-not $KeepCache) {
    Remove-Item $cacheDir -Recurse -Force
}
